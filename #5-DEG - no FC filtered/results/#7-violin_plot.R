violin <- function(x){
  png(filename = paste0("./vlnplot/circadian_genes_not_found_in_bulkseq/violin_",x,"_all.png"),
      width = 3000,
      height = 1000)
  p <- VlnPlot(so, features = x, split.by = "group_id") +
    theme(text = element_text(size = 40),
          axis.text.x.bottom = element_text(size = 40, angle = 90))
  print(p)
  dev.off()
  png(filename = paste0("./vlnplot/violin_",x,"_interneuron.png"),
      width = 3000,
      height = 1000)
  p <- VlnPlot(so, features = x, split.by = "group_id", idents = "Interneuron") +
    theme(text = element_text(size = 40),
          axis.text.x.bottom = element_text(size = 40))
  print(p)
  dev.off()
}

